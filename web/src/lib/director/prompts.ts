/** 输入类型说明：剧本的场次是现成的，小说的场次要模型自己切。 */
function sourceIntro(sourceLabel: string, kind: DirectorScriptKind) {
    if (kind === "script") {
        return [
            `下面是一段剧本（${sourceLabel}）。请一次拆出三类制作资产：**人物**、**场景**、**重要物品**。`,
            "",
            "注意：这是剧本，场次已经由剧本本身切好了 —— 本段通常就是一场。",
            "本段只有一场就只输出一个场景；确实包含多场才按剧本的场次切分。不要合并场次，也不要自行拆出新场次。",
        ];
    }
    return [`请从下面这段小说文本（${sourceLabel}）里，一次拆出三类制作资产：**人物**、**场景**、**重要物品**。`];
}

/** 第一步：从一段文本里一次拆出人物 / 场景 / 重要物品。 */
export function buildAssetExtractPrompt(sourceLabel: string, text: string, kind: DirectorScriptKind = "novel") {
    return [
        ...sourceIntro(sourceLabel, kind),
        "",
        "一、人物",
        "1. 只提取真正有戏份的人物。只露面一次、没有名字的功能性角色（如「店员」「路人甲」）不要单列。",
        "2. 分级只有两种：主角（推动主线、反复出场）/ 配角（有名字，有对白或明确作用）。",
        "3. 外貌必须具体到能画出来：发型发色、脸型五官、体型身高、常穿服饰、标志特征。",
        "   小说没写外貌时，按身份和年龄合理设定一套；不要写「长相清秀」「气质出众」这类无法作画的词。",
        "4. 关系只写与本文本中已列出人物的关系，写清关系类型 + 现状。",
        "",
        "二、场景",
        "1. **同一连续时空算一场**：不换地点、不跳时间就是同一场；换地点、跳时间、或剧情明显转折就切新场。",
        "2. 按剧情先后顺序输出，不要打乱。",
        "3. 「出场人物」只写这一场真正出现的人，必须与人物区块里的姓名完全一致，用「、」分隔。",
        "4. 「出现物品」只写这一场里**有画面作用**的重要物品（信物、道具、关键物件），日常背景物不用写。",
        "   必须与物品区块里的名称完全一致。",
        "5. 「本场造型」写这一场该用人物表里的哪套服饰（例如「日常」「校服」），没变化就写「默认」。",
        "",
        "三、重要物品",
        "1. 只提取**推动剧情或有象征意义**的物品（信、钥匙、戒指、旧照片、武器等）。",
        "   日常背景物（杯子、椅子）不要列。",
        "2. 外观要具体到能画出来：形状、颜色、尺寸、磨损痕迹、标志性细节。",
        "",
        "四、通用要求",
        "1. 三类资产的生图提示词：只写**外观**（外形 / 材质 / 颜色 / 画面质感），不要写动作、场景、镜头。",
        "2. 没有内容的字段写「无」，不要留空。",
        "3. 三个区块必须都输出，即使某一类为空也要保留区块标记。",
        "",
        CONCRETE_RULE,
        "",
        ASSET_FORMAT,
        "",
        "待分析文本：",
        '"""',
        text,
        '"""',
    ].join("\n");
}

/** 第一步（长篇小说）：把分批提取的三类资产合并去重。 */
export function buildAssetMergePrompt(partials: string[]) {
    return [
        "下面是同一部小说分批提取出的「人物 / 场景 / 重要物品」清单。",
        "同一个人物或物品可能出现在多批里，而且叫法不同（例如「小满」「林小满」「满姐」是同一个人）。",
        "请合并成一份统一的清单。",
        "",
        "要求：",
        "1. 输出必须保留三个区块标记 ### 人物 / ### 场景 / ### 物品，顺序不变。",
        "2. **人物、物品**：认出是同一条的必须合并。姓名 / 名称统一用全名，其它叫法放进「称呼」。",
        "3. **场景不要合并**：场景是按剧情顺序发生的时空单元，同一地点在不同时间就是不同场景。",
        "   按剧情顺序原样保留，只去掉完全重复的相邻条目。",
        "4. 合并时信息取并集；同一字段冲突时保留更具体、更早出现的那一版。",
        "5. 人物重新分级：跨批次反复出现、推动主线的才是主角，其余为配角。删掉纯功能性角色。",
        "6. 关系字段里如果引用了被合并掉的旧名字，改写成合并后的全名。",
        "7. 输出格式与输入完全一致，不要任何解释。",
        "",
        ASSET_FORMAT,
        "",
        "待合并的清单：",
        "==========",
        partials.join("\n\n==========\n\n"),
        "==========",
    ].join("\n");
}

/** 第二步：只为已经定下来的场景写分镜。 */
export function buildShotPrompt(options: { sourceTitle: string; sourceText: string; sceneList: string; roster: string; shotsPerScene: number }) {
    const { sourceTitle, sourceText, sceneList, roster, shotsPerScene } = options;
    const shotHint = shotsPerScene > 0 ? `每场约 ${shotsPerScene} 个分镜（可按剧情密度上下浮动）` : "每场一般 2~12 个分镜，由剧情密度决定";

    return [
        "请为下面已经定好的每一场，写它的分镜。",
        "",
        "一、场景已经定好了，不要新增或改名",
        "严格按给出的场景名输出，每场一个区块。场景名必须一字不差。",
        "",
        "二、每场分镜数量",
        `${shotHint}。`,
        "- 有对白、动作、情绪转折的地方多拆几个",
        "- 纯过场、交代性的内容少拆几个",
        "不要为了凑数硬拆，也不要漏掉关键动作。",
        "",
        "三、字段说明",
        "- 生成类型：这一镜该「图」还是「视频」。",
        "  静态画面、纯对话、气氛空镜 → 写「图」",
        "  有动作、有运镜、有连续变化、有情绪爆发的镜头 → 写「视频」",
        "- 景别：远景 / 全景 / 中景 / 近景 / 特写 / 大特写",
        "- 机位高度：平视 / 略高 / 俯拍 / 仰拍",
        "- 机位角度：正面 / 侧面 / 背面 / 过肩 / 主观视角",
        "- 运镜：固定 / 推 / 拉 / 摇 / 移 / 跟 / 升降 / 手持",
        "- 画面：谁、在哪、做什么、什么表情动作 —— 写到能直接开拍",
        "- 台词：写成「角色名：台词内容」；没有说话就写「无」",
        "- 生图提示词：**只写镜头、构图、光线、色调、环境氛围**，",
        "  **严禁写人物外貌**（外貌由人物表单独提供，两边都写会互相打架）",
        "",
        "四、人物一致性（重要）",
        "只能使用下面人物表里已有的姓名，不要自己造名字，也不要写简称。",
        "台词说话人必须是该场「出场人物」里的人。",
        "",
        CONCRETE_RULE,
        "",
        "输出格式（严格照抄，不要输出任何其它文字）：",
        "=== 场景名（与下面给出的场景名完全一致）",
        "--- 分镜",
        "生成类型：图 / 视频",
        "时长：约 X 秒",
        "景别：",
        "机位高度：",
        "机位角度：",
        "运镜：",
        "构图：",
        "画面：",
        "情绪：",
        "台词：",
        "旁白：",
        "音效：",
        "配乐：",
        "节奏：快 / 中 / 慢",
        "转场：",
        "生图提示词：",
        "",
        "--- 分镜",
        "（同一场的下一个分镜，格式同上）",
        "",
        "=== 场景名",
        "（下一场，格式同上）",
        "",
        "没有内容的字段写「无」，不要留空。",
        "",
        "本段的场景清单：",
        "==========",
        sceneList,
        "==========",
        "",
        "人物表：",
        "==========",
        roster,
        "==========",
        "",
        `本段标题：${sourceTitle}`,
        "本段原文：",
        '"""',
        sourceText,
        '"""',
    ].join("\n");
}
