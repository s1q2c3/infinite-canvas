/**
 * 导演台提示词。
 *
 * 拆解质量几乎全靠这里。核心是两条：
 * 1. 强制「可见可听」并给反面例子 —— 不给反面例子，模型一定写"气氛紧张"这种空话。
 * 2. 外貌只在人物表定义一次，分镜只引用不重写 —— 否则同一个人前后换脸。
 */

/** 三个拆解步骤共用的系统提示。 */
export const DIRECTOR_SYSTEM_PROMPT = [
    "你是一位专业的影视剧本分析师与分镜师，擅长把小说转化成可以直接开拍的制作资料。",
    "你的输出必须严格遵守用户给定的格式：不要添加任何解释、前言、总结，不要使用 Markdown 代码块。",
    "所有描述必须具体到「看得见、听得到」，禁止使用抽象的情绪词。",
].join("\n");

/** 具体化要求：正反例是这段的关键，别删。 */
const CONCRETE_RULE = [
    "必须具体，禁止空话：",
    '❌ 不要写"气氛紧张" → ✅ 要写"雨水打在铁皮雨棚上，声音盖过了两人说话"',
    '❌ 不要写"她很难过" → ✅ 要写"她盯着地面，拇指反复搓着钥匙扣"',
    '❌ 不要写"画面很美" → ✅ 要写"便利店的白色灯管在她侧脸投下一道硬边阴影"',
].join("\n");

const CHARACTER_FORMAT = [
    "输出格式（严格照抄字段名与顺序，人物之间用单独一行 --- 分隔，不要输出任何其它文字）：",
    "姓名：",
    "分级：主角 / 配角",
    "称呼：",
    "身份：",
    "年龄：",
    "外貌：",
    "服饰：",
    "标志特征：",
    "音色语气：",
    "性格：",
    "前史：",
    "动机：",
    "关系：",
    "弧光：",
    "生图提示词：",
].join("\n");

/** 第一步 A：从一段（章或全书）文本里提取人物。 */
export function buildCharacterExtractPrompt(sourceLabel: string, text: string) {
    return [
        `请从下面这段小说文本（${sourceLabel}）中提取出场人物，并为每个人物填写设定。`,
        "",
        "要求：",
        "1. 只提取真正有戏份的人物。只露面一次、没有名字的功能性角色（如「店员」「路人甲」）不要单列。",
        "2. 分级只有两种：主角（推动主线、反复出场）/ 配角（有名字，有对白或明确作用）。其余一律不列。",
        "3. 外貌必须具体到能画出来：发型发色、脸型五官、体型身高、常穿服饰、标志特征。",
        "   小说没写外貌时，按身份和年龄合理设定一套，并且要具体；",
        '   不要写"长相清秀""气质出众"这类无法作画的词。',
        "4. 关系只写与本文本中已列出人物的关系，写清关系类型 + 现状。",
        "5. 生图提示词：一条能直接出图的外观描述，只写年龄 / 性别 / 发型 / 脸型 / 服饰 / 画面质感，",
        "   不要写动作、场景、镜头。",
        "6. 没有内容的字段写「无」，不要留空。",
        "",
        CONCRETE_RULE,
        "",
        CHARACTER_FORMAT,
        "",
        "待分析文本：",
        '"""',
        text,
        '"""',
    ].join("\n");
}

/** 第一步 B：把分批提取的人物表合并去重（长篇小说需要）。 */
export function buildCharacterMergePrompt(partials: string[]) {
    return [
        "下面是同一部小说分批提取出的人物设定。同一个人物可能出现在多批里，而且叫法不同",
        "（例如「小满」「林小满」「满姐」是同一个人）。请合并成一份统一的人物表。",
        "",
        "要求：",
        "1. 认出是同一个人物的必须合并成一条。姓名统一用全名，其它叫法全部放进「称呼」。",
        "2. 合并时信息取并集；同一个字段有冲突时，保留更具体、更早出现的那一版。",
        "3. 重新分级：跨批次反复出现、推动主线的才是主角，其余为配角。",
        "4. 删掉重复条目和纯功能性角色。",
        "5. 关系字段里如果引用了被合并掉的旧名字，改写成合并后的全名。",
        "6. 输出格式与输入完全一致，不要任何解释。",
        "",
        CHARACTER_FORMAT,
        "",
        "待合并的人物表：",
        "==========",
        partials.join("\n\n==========\n\n"),
        "==========",
    ].join("\n");
}

/** 第二步：把一章拆成场景与分镜。 */
export function buildSceneShotPrompt(options: { chapterTitle: string; chapterText: string; roster: string; shotsPerChapter: number }) {
    const { chapterTitle, chapterText, roster, shotsPerChapter } = options;
    const shotHint = shotsPerChapter > 0 ? `本章期望约 ${shotsPerChapter} 个分镜（可按剧情密度上下浮动）` : "一般 2~12 个分镜，由剧情密度决定";

    return [
        "请把下面这一章小说拆成【场景】和【分镜】。",
        "",
        "一、场景怎么切",
        "同一连续时空算一场：不换地点、不跳时间，就是同一场。",
        "换地点、跳时间、或剧情明显转折 → 切新场。",
        "",
        "二、每场分镜数量",
        `${shotHint}。`,
        "- 有对白、动作、情绪转折的地方多拆几个",
        "- 纯过场、交代性的内容少拆几个",
        "不要为了凑数硬拆，也不要漏掉关键动作。",
        "",
        "三、字段说明",
        "- 景别：远景 / 全景 / 中景 / 近景 / 特写 / 大特写",
        "- 机位高度：平视 / 略高 / 俯拍 / 仰拍",
        "- 机位角度：正面 / 侧面 / 背面 / 过肩 / 主观视角",
        "- 运镜：固定 / 推 / 拉 / 摇 / 移 / 跟 / 升降 / 手持",
        "- 画面：谁、在哪、做什么、什么表情动作 —— 写到能直接开拍",
        "- 台词：写成「角色名：台词内容」；没有说话就写「无」",
        "- 生图提示词：**只写镜头、构图、光线、色调、环境氛围**，",
        "  **严禁写人物外貌**（外貌由人物表单独提供，两边都写会互相打架）",
        "",
        "四、人物一致性（重要）",
        "只能使用下面人物表里已有的姓名，不要自己造名字，也不要写简称。",
        "「出场人物」只写这一场真正出现的人，用「、」分隔，必须与人物表姓名完全一致。",
        "「本场造型」写这一场该用人物表里的哪套服饰（例如「日常」「校服」），没变化就写「默认」。",
        "",
        CONCRETE_RULE,
        "",
        "输出格式（严格照抄字段名与顺序，不要输出任何其它文字）：",
        "=== 场景",
        "场景名：",
        "地点：",
        "时间：",
        "内外景：内景 / 外景",
        "季节天气：",
        "氛围：",
        "光线：",
        "色调：",
        "关键道具：",
        "本场造型：",
        "场景目标：",
        "冲突：",
        "结果：",
        "出场人物：",
        "生图提示词：",
        "",
        "--- 分镜",
        "时长：约 X 秒",
        "景别：",
        "机位高度：",
        "机位角度：",
        "运镜：",
        "构图：",
        "画面：",
        "情绪：",
        "台词：",
        "旁白：",
        "音效：",
        "配乐：",
        "节奏：快 / 中 / 慢",
        "转场：",
        "生图提示词：",
        "",
        "--- 分镜",
        "（同一场的下一个分镜，格式同上）",
        "",
        "=== 场景",
        "（下一场，格式同上）",
        "",
        "没有内容的字段写「无」，不要留空。",
        "",
        "人物表：",
        "==========",
        roster,
        "==========",
        "",
        `章节标题：${chapterTitle}`,
        "章节原文：",
        '"""',
        chapterText,
        '"""',
    ].join("\n");
}
